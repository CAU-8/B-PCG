def elevation_land_text(z_name: str, mean_fraction: float | None) -> str:
    """고도 설명의 육지 문장. 실제로 쓴 고도 필드(z_mean_m 또는 z_m)를 밝힙니다."""
    if z_name == "z_mean_m":
        frac = "일부" if mean_fraction is None else f"{mean_fraction:g} 배"
        return f"육지는 칸 평균 지표 고도(z_mean_m = 골짜기 바닥 z_m + 칸 안 기복의 {frac})입니다."
    return (
        f"육지는 L0 칸의 골짜기 바닥 고도({z_name})입니다. 이 묶음에는 칸 평균 지표(z_mean_m)가 "
        "없어 칸 안 기복을 더하지 않았으므로, 실제 평균 지표보다 조금 낮습니다."
    )


def relief_hydro_note(
    mean_fraction: float | None, gap_m: float | None, valley_ratio: float | None
) -> str:
    """칸 안 기복 설명에 덧붙이는 물 이야기 (지하수면 깊이·골짜기 깊이를 따로 싣지 않는 까닭).

    gap_m: 육지 칸의 (골짜기 바닥 − 지하수면) 가운데값 [m]. valley_ratio: 육지 칸의
    (골짜기 깊이 / 칸 안 기복) 가운데값. 모르면 None (그 문장을 뺍니다).
    """
    parts = []
    if gap_m is not None:
        frac = "mean_fraction" if mean_fraction is None else f"{mean_fraction:g}"
        parts.append(
            f" L0 에서는 지하수면이 골짜기 바닥에 붙어 있어(둘의 차 가운데값 {gap_m:.2g} m), "
            f"지표에서 지하수면까지의 칸 평균 깊이는 거의 {frac} × 칸 안 기복입니다."
        )
    if valley_ratio is not None:
        parts.append(
            " 동굴 위층의 높이를 정하는 골짜기 깊이(valley_depth_m)도 L0 에서는 칸 안 기복과 거의 "
            f"같습니다(가운데값 비 {valley_ratio:.2f})."
        )
    if parts:
        parts.append(" 그래서 두 값은 따로 싣지 않고 이 레이어로 읽습니다.")
    return "".join(parts)


def uplift_how(lo_end: float, hi_end: float, has_neg: bool, has_pos: bool) -> str:
    """융기 속도 읽는 법. lo_end, hi_end 는 실제 색표의 양 끝 [mm/yr]."""
    if not has_neg and not has_pos:
        return "모든 칸의 융기 속도가 0 이라 흰색 한 가지입니다."
    out = "흰색은 거의 0(안정한 땅)입니다."
    if has_pos:
        out += f" 주황 → 짙은 갈색으로 갈수록 빨리 솟습니다(짙은 갈색 ≈ {hi_end:.2g} mm/yr 이상)."
    else:
        out += " 솟는 곳이 없어 주황·갈색은 쓰지 않습니다."
    if has_neg:
        out += f" 보라는 가라앉는 곳입니다(진한 보라 ≈ {lo_end:.2g} mm/yr 이하)."
    else:
        out += " 가라앉는 곳이 없어 보라색은 쓰지 않습니다."
    if has_neg and has_pos:
        out += " 솟는 쪽과 가라앉는 쪽은 눈금 크기가 달라 0 을 기준으로 따로 읽습니다."
    return out


def temperature_how(lo_end: float, hi_end: float, t_min: float, t_max: float) -> str:
    """기온 읽는 법. lo_end, hi_end 는 실제 색표의 양 끝, t_min, t_max 는 자료의 끝 [°C]."""
    out = "흰색이 0 °C(어는점)입니다."
    if lo_end < 0.0:
        out += f" 파랑이 진할수록 춥습니다(가장 진한 파랑 ≈ {lo_end:.0f} °C 이하)."
    else:
        out += f" 영하인 곳이 없어 파랑은 쓰지 않습니다(가장 추운 곳 ≈ {t_min:.0f} °C)."
    if hi_end > 0.0:
        out += f" 빨강이 진할수록 덥습니다(가장 진한 빨강 ≈ {hi_end:.0f} °C 이상)."
    else:
        out += f" 영상인 곳이 없어 빨강은 쓰지 않습니다(가장 더운 곳 ≈ {t_max:.0f} °C)."
    return out
